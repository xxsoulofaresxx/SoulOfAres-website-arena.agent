export function formatPrice(priceEUR: number, currency: string): string {
  const { rate, symbol } = EXCHANGE_RATES[currency] ?? EXCHANGE_RATES.EUR;
  const converted = Math.round(priceEUR * rate);
  return `${symbol}${converted}`;
}
